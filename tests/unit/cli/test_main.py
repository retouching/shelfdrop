"""The `shelfdrop` command."""

import json
import logging
import os
from pathlib import Path

import pytest
from alembic.util.exc import AutogenerateDiffsDetected

from shelfdrop.cli import main as cli
from shelfdrop.config import Settings


@pytest.fixture
def contact(monkeypatch: pytest.MonkeyPatch) -> None:
    monkeypatch.setenv("SHELFDROP_CONTACT", "test@example.org")


@pytest.mark.usefixtures("isolated_logging", "contact")
def test_db_upgrade_applies_the_migrations(monkeypatch: pytest.MonkeyPatch) -> None:
    calls: list[str] = []
    monkeypatch.setattr(cli, "upgrade_database", lambda: calls.append("upgrade"))

    assert cli.main(["db", "upgrade"]) == 0
    assert calls == ["upgrade"]


@pytest.mark.usefixtures("isolated_logging", "contact")
def test_db_check_says_when_the_database_matches(
    monkeypatch: pytest.MonkeyPatch, capsys: pytest.CaptureFixture[str]
) -> None:
    monkeypatch.setattr(cli, "check_database", lambda: None)

    assert cli.main(["db", "check"]) == 0
    assert capsys.readouterr().out == "the database matches the models\n"


@pytest.mark.usefixtures("isolated_logging", "contact")
def test_db_check_fails_on_a_difference(
    monkeypatch: pytest.MonkeyPatch, capsys: pytest.CaptureFixture[str]
) -> None:
    def differs() -> None:
        # Built without its arguments: the command reads none of them.
        raise AutogenerateDiffsDetected.__new__(AutogenerateDiffsDetected)

    monkeypatch.setattr(cli, "check_database", differs)

    assert cli.main(["db", "check"]) == 1
    assert capsys.readouterr().err == "error: the database differs from the models\n"


def test_a_command_is_required(capsys: pytest.CaptureFixture[str]) -> None:
    with pytest.raises(SystemExit):
        cli.main([])
    assert "usage: shelfdrop" in capsys.readouterr().err


@pytest.mark.usefixtures("isolated_logging", "contact")
def test_the_placement_worker_logs_to_its_file_too(
    monkeypatch: pytest.MonkeyPatch, tmp_path: Path
) -> None:
    monkeypatch.setenv("SHELFDROP_DATA_DIR", str(tmp_path))
    # The umask of the worker is not left on the process of the tests.
    monkeypatch.setattr(os, "umask", lambda mask: mask)

    async def run(settings: Settings) -> None:
        logging.getLogger("shelfdrop.placement.worker").info("Placement worker started")

    monkeypatch.setattr(cli, "run_placement", run)

    assert cli.main(["placement", "run"]) == 0
    for handler in logging.getLogger().handlers:
        handler.flush()
    lines = (tmp_path / "logs" / "placement.jsonl").read_text(encoding="utf-8").splitlines()
    assert [json.loads(line)["message"] for line in lines] == ["Placement worker started"]


@pytest.mark.usefixtures("isolated_logging", "contact")
def test_a_command_of_the_database_writes_no_file(
    monkeypatch: pytest.MonkeyPatch, tmp_path: Path
) -> None:
    monkeypatch.setenv("SHELFDROP_DATA_DIR", str(tmp_path))
    monkeypatch.setattr(cli, "upgrade_database", lambda: None)

    assert cli.main(["db", "upgrade"]) == 0
    assert not (tmp_path / "logs").exists()
