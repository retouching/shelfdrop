"""`shelfdrop`: the command line of the operator: the migrations of the database, and the
placement worker."""

import argparse
import asyncio
import os
import sys
from collections.abc import Sequence

from alembic.util.exc import AutogenerateDiffsDetected

from shelfdrop.config import Settings
from shelfdrop.container import run_placement
from shelfdrop.db.migrate import check_database, upgrade_database
from shelfdrop.logging.setup import configure_logging


def parser() -> argparse.ArgumentParser:
    root = argparse.ArgumentParser(prog="shelfdrop")
    commands = root.add_subparsers(dest="command", required=True)
    database = commands.add_parser("db", help="the database")
    actions = database.add_subparsers(dest="action", required=True)
    actions.add_parser("upgrade", help="apply every pending migration")
    actions.add_parser("check", help="compare the database with the models")
    placement = commands.add_parser("placement", help="the placement of the downloads")
    jobs = placement.add_subparsers(dest="action", required=True)
    jobs.add_parser("run", help="place the downloads complete, until stopped")
    return root


def main(arguments: Sequence[str] | None = None) -> int:
    parsed = parser().parse_args(arguments)
    settings = Settings()
    configure_logging(level=settings.log_level, json_format=settings.log_format == "json")
    if parsed.command == "placement":
        # The folders and the files of the shelf are writable by the group of the library.
        os.umask(0o002)
        asyncio.run(run_placement(settings))
        return 0
    if parsed.action == "upgrade":
        upgrade_database()
        return 0
    try:
        check_database()
    except AutogenerateDiffsDetected:
        sys.stderr.write("error: the database differs from the models\n")
        return 1
    sys.stdout.write("the database matches the models\n")
    return 0


if __name__ == "__main__":
    sys.exit(main())
