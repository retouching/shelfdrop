"""Schema migrations: apply the Alembic revisions of shelfdrop/db/migrations, and compare the
database with the models."""

from pathlib import Path
from typing import Final

from alembic import command
from alembic.config import Config

MIGRATIONS_DIR: Final = Path(__file__).resolve().parent / "migrations"


def migrations_config() -> Config:
    config = Config()
    config.set_main_option("script_location", str(MIGRATIONS_DIR))
    config.set_main_option("path_separator", "os")
    return config


def upgrade_database() -> None:
    """Apply every pending Alembic revision; the URL comes from Settings (see migrations/env.py)."""
    command.upgrade(migrations_config(), "head")


def check_database() -> None:
    """Compare the database with the models; raises AutogenerateDiffsDetected on a difference
    (`alembic check`, without the alembic.ini of the repository)."""
    command.check(migrations_config())
